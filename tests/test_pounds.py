def test_a_row_whose_date_lost_its_rate_says_so_instead_of_counting_zero(
        client, booking, ctx):
    """A stored row is only dollars and a date. If the rate file later stops
    covering that date, the row must say it cannot be converted rather than
    contribute nothing silently and quietly shrink the total."""
    from core import database as db
    from domain import pounds

    db.insert(
        """INSERT INTO pound_conversions
           (user_id, spent_on, description, category, cad_cents)
           VALUES (?, ?, ?, ?, ?)""",
        (booking["user"]["id"], "2027-01-02", "Later than the file", None,
         50000))

    listed = client.get("/api/pounds", headers=booking["auth"]).get_json()
    assert len(listed["conversions"]) == 1
    assert "error" in listed["conversions"][0], listed["conversions"][0]
    assert "pence" not in listed["conversions"][0]
    assert listed["spentPence"] == 0
    assert pounds.spent(booking["user"]["id"]) == 0


# -------------------------------------------------------------- the quote


def test_a_quote_costs_nothing_and_records_nothing(client, booking):
    got = client.get(f"/api/pounds/quote?cadCents=100000&on={FRIDAY}",
                     headers=booking["auth"])
    assert got.status_code == 200
    quote = got.get_json()["quote"]
    assert quote["cadCents"] == 100000
    assert quote["feePence"] > 0
    assert quote["referencePence"] > quote["pence"], (
        "the markup should leave you with less than the reference rate")
    assert quote["fits"] is True
    assert quote["rateDate"] == FRIDAY

    listed = client.get("/api/pounds", headers=booking["auth"]).get_json()
    assert listed["conversions"] == [], "a quote recorded something"


def test_a_quote_says_when_it_would_not_fit(client, booking):
    """The page has to say "that would put you over" before the button is
    pressed, not after the request comes back refused."""
    auth_post(client, booking, spentOn=FRIDAY, description="Rent",
              cadCents=180000)
    got = client.get(f"/api/pounds/quote?cadCents=100000&on={FRIDAY}",
                     headers=booking["auth"]).get_json()["quote"]
    assert got["fits"] is False
    assert got["remainingPence"] < got["pence"]


def test_a_quote_refuses_an_amount_it_cannot_read(client, booking):
    for query in ("cadCents=&on=" + FRIDAY, "cadCents=lots&on=" + FRIDAY,
                  "cadCents=-500&on=" + FRIDAY, "cadCents=100&on=nonsense"):
        got = client.get(f"/api/pounds/quote?{query}",
                         headers=booking["auth"])
        assert got.status_code == 400, f"{query} was accepted"
